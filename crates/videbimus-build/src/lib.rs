//! Per-kind code identity, from a build script ([ADR 0009] §5).
//!
//! Every asset's key includes the code identity of the kind that built it,
//! so editing a kind's code rebuilds what that kind built, and nothing
//! else. Hashing the whole binary would rebuild everything on any edit;
//! instead each kind declares the source files its output depends on, and
//! this crate hashes them into one constant per kind at build time.
//!
//! In the kind crate's `build.rs`:
//!
//! ```no_run
//! // fn main() {
//! videbimus_build::Kinds::new()
//!     .kind("fen", &["src/fen.rs", "src/fen/"])   // a file, or a directory
//!     .kind("song-render", &["src/song.rs"])
//!     .write();
//! // }
//! ```
//!
//! and in the crate, the generated constants (`FEN`, `SONG_RENDER`: the
//! kind's name in upper case, with `-` as `_`) feed the kinds' `CODE`:
//!
//! ```ignore
//! mod code {
//!     videbimus::include_code!();
//! }
//!
//! impl videbimus::RecipeKind for SongRender {
//!     const KIND: &'static str = "song-render";
//!     const CODE: &'static str = code::SONG_RENDER;
//!     // const VERSION: &'static str = "2"; // bump to force a rebuild
//!     // ...
//! }
//! ```
//!
//! Paths are relative to the crate's directory (`CARGO_MANIFEST_DIR`). A
//! directory stands for every file under it. The hash covers each file's
//! path (relative, with `/`, so it is the same on every machine) and
//! contents, in sorted order, so it changes when a declared file is
//! edited, added, removed or renamed, and for nothing else. Cargo is told
//! to rerun the build script when any declared path changes.
//!
//! What the hash can't see, such as a dependency's new version or a
//! shared module that isn't declared, is what a kind's `VERSION` is for.
//!
//! [ADR 0009]: ../../../adrs/0009-using-videbimus.md

use std::fmt;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// The file [`Kinds::write`] generates in `OUT_DIR`.
pub const GENERATED_FILE: &str = "videbimus_code.rs";

/// A kind's declared sources couldn't be hashed.
#[derive(Debug)]
pub struct Error {
    /// The kind.
    pub kind: String,
    /// The path, as declared.
    pub path: String,
    /// What went wrong.
    pub source: io::Error,
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "kind `{}`: can't hash `{}`: {}; declare paths relative to the crate's directory (where Cargo.toml is)",
            self.kind, self.path, self.source
        )
    }
}

impl std::error::Error for Error {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        Some(&self.source)
    }
}

/// The kinds a crate defines, and the source files each declares.
#[derive(Clone, Debug, Default)]
#[must_use]
pub struct Kinds {
    kinds: Vec<(String, Vec<String>)>,
}

impl Kinds {
    /// No kinds yet.
    pub fn new() -> Self {
        Self::default()
    }

    /// Kind `kind` (its name in config) depends on `paths`: files or
    /// directories, relative to the crate's directory.
    ///
    /// # Panics
    ///
    /// If `kind` is declared twice, or has no paths.
    pub fn kind(mut self, kind: &str, paths: &[&str]) -> Self {
        assert!(
            !self.kinds.iter().any(|(k, _)| k == kind),
            "videbimus-build: kind `{kind}` is declared twice; declare each kind once, with all its paths"
        );
        assert!(
            !paths.is_empty(),
            "videbimus-build: kind `{kind}` declares no source paths; give at least its own module"
        );
        self.kinds.push((
            kind.to_owned(),
            paths.iter().map(|&p| p.to_owned()).collect(),
        ));
        self
    }

    /// Each kind's identity, hashing paths under `root`, in declaration
    /// order.
    ///
    /// # Errors
    ///
    /// The first path that can't be read.
    pub fn identities(&self, root: &Path) -> Result<Vec<(String, String)>, Error> {
        self.kinds
            .iter()
            .map(|(kind, paths)| {
                let refs: Vec<&str> = paths.iter().map(String::as_str).collect();
                hash_sources(root, &refs)
                    .map(|h| (kind.clone(), h))
                    .map_err(|(path, source)| Error {
                        kind: kind.clone(),
                        path,
                        source,
                    })
            })
            .collect()
    }

    /// The Rust source of the generated file: one `pub const` per kind,
    /// named by [`const_name`], holding its identity as hex.
    ///
    /// # Errors
    ///
    /// As [`identities`](Self::identities).
    pub fn generate(&self, root: &Path) -> Result<String, Error> {
        let mut out = String::from(
            "// Generated by videbimus-build from the kinds' declared source files. Do not edit.\n",
        );
        for ((kind, hash), (_, paths)) in self.identities(root)?.into_iter().zip(&self.kinds) {
            let _ = writeln!(
                out,
                "/// The code identity of kind `{kind}`: a hash of {}.\npub const {}: &str = \"{hash}\";",
                paths
                    .iter()
                    .map(|p| format!("`{p}`"))
                    .collect::<Vec<_>>()
                    .join(", "),
                const_name(&kind),
            );
        }
        Ok(out)
    }

    /// From a build script: writes [`GENERATED_FILE`] into `OUT_DIR`, and
    /// tells Cargo to rerun when a declared path changes.
    ///
    /// # Panics
    ///
    /// Outside a build script (no `CARGO_MANIFEST_DIR` or `OUT_DIR`), or
    /// if a path can't be read or the file can't be written; the message
    /// names the kind and path. A build script can only report by
    /// failing.
    pub fn write(self) {
        let var = |name: &str| {
            std::env::var_os(name).map_or_else(
                || panic!("videbimus-build: `{name}` isn't set; call Kinds::write from a build script (build.rs)"),
                PathBuf::from,
            )
        };
        let root = var("CARGO_MANIFEST_DIR");
        let out = var("OUT_DIR");
        for (_, paths) in &self.kinds {
            for p in paths {
                println!("cargo::rerun-if-changed={p}");
            }
        }
        let source = self
            .generate(&root)
            .unwrap_or_else(|e| panic!("videbimus-build: {e}"));
        let path = out.join(GENERATED_FILE);
        if let Err(e) = fs::write(&path, source) {
            panic!("videbimus-build: can't write {}: {e}", path.display());
        }
    }
}

/// The constant [`Kinds::generate`] names for `kind`: upper case, with
/// every character that can't be in an identifier as `_`, and a leading
/// `_` if it would start with a digit. `song-render` is `SONG_RENDER`.
#[must_use]
pub fn const_name(kind: &str) -> String {
    let mut s: String = kind
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.is_empty() || s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}

/// The hash of `paths` (files or directories, relative to `root`), as 64
/// hex digits. Directories stand for every file under them; files are
/// hashed by relative path and contents, in sorted order, each once.
///
/// # Errors
///
/// The declared path that failed, with the error.
pub fn hash_sources(root: &Path, paths: &[&str]) -> Result<String, (String, io::Error)> {
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    for &p in paths {
        let full = root.join(p);
        let meta = fs::metadata(&full).map_err(|e| (p.to_owned(), e))?;
        if meta.is_dir() {
            walk(root, &full, &mut files).map_err(|e| (p.to_owned(), e))?;
        } else {
            files.push((portable(root, &full), full));
        }
    }
    files.sort();
    files.dedup_by(|a, b| a.0 == b.0);
    let mut h = blake3::Hasher::new_derive_key("videbimus 2026-11-18 code identity v1");
    for (label, path) in &files {
        let bytes = fs::read(path).map_err(|e| (label.clone(), e))?;
        h.update(&(label.len() as u64).to_le_bytes());
        h.update(label.as_bytes());
        h.update(&(bytes.len() as u64).to_le_bytes());
        h.update(&bytes);
    }
    Ok(h.finalize().to_hex().to_string())
}

fn walk(root: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) -> io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            walk(root, &path, files)?;
        } else {
            files.push((portable(root, &path), path));
        }
    }
    Ok(())
}

/// `path` relative to `root`, with `/` between components.
fn portable(root: &Path, path: &Path) -> String {
    let rel = path.strip_prefix(root).unwrap_or(path);
    rel.components()
        .map(|c| c.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert_eq!(const_name("song-render"), "SONG_RENDER");
        assert_eq!(const_name("fen"), "FEN");
        assert_eq!(const_name("3d.shot"), "_3D_SHOT");
    }

    #[test]
    fn editing_one_kind_changes_only_its_identity() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        fs::write(root.join("a.rs"), "fn a() {}").unwrap();
        fs::create_dir(root.join("b")).unwrap();
        fs::write(root.join("b/one.rs"), "fn one() {}").unwrap();
        let kinds = Kinds::new().kind("a", &["a.rs"]).kind("b", &["b"]);
        let before = kinds.identities(root).unwrap();
        assert_eq!(before.len(), 2);
        assert_eq!(before[0].1.len(), 64);
        assert_eq!(kinds.identities(root).unwrap(), before, "stable");

        fs::write(root.join("a.rs"), "fn a() { /* edited */ }").unwrap();
        let after = kinds.identities(root).unwrap();
        assert_ne!(after[0], before[0]);
        assert_eq!(after[1], before[1]);

        // a file added under a declared directory changes that kind only
        fs::write(root.join("b/two.rs"), "fn two() {}").unwrap();
        let added = kinds.identities(root).unwrap();
        assert_eq!(added[0], after[0]);
        assert_ne!(added[1], after[1]);
    }

    #[test]
    fn moving_the_crate_keeps_identities() {
        let (x, y) = (tempfile::tempdir().unwrap(), tempfile::tempdir().unwrap());
        for d in [x.path(), y.path()] {
            fs::write(d.join("k.rs"), "fn k() {}").unwrap();
        }
        let kinds = Kinds::new().kind("k", &["k.rs"]);
        assert_eq!(
            kinds.identities(x.path()).unwrap(),
            kinds.identities(y.path()).unwrap()
        );
    }

    #[test]
    fn generated_source() {
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("s.rs"), "").unwrap();
        let src = Kinds::new()
            .kind("song-render", &["s.rs"])
            .generate(dir.path())
            .unwrap();
        assert!(src.contains("pub const SONG_RENDER: &str = \""), "{src}");
    }

    #[test]
    fn missing_path_names_kind_and_path() {
        let dir = tempfile::tempdir().unwrap();
        let e = Kinds::new()
            .kind("fen", &["src/fen.rs"])
            .identities(dir.path())
            .unwrap_err();
        let msg = e.to_string();
        assert!(
            msg.starts_with("kind `fen`: can't hash `src/fen.rs`: "),
            "{msg}"
        );
    }
}
